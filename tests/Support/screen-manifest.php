|--------------------------------------------------------------------------
| Screen manifest (D60; phase-24-25 §6.1, §13.2; build-order E4)
|--------------------------------------------------------------------------
|
| One row per GET route a phase ships — the data provider of every screen sweep: query budgets (PRF-01),
| responsive (RSP-*), accessibility (A11Y-*) and IDOR (ISO-*). Phase 24's `audit:manifest --check` fails on
| a GET route with no row and on a row whose route no longer exists.
|
| Append-only per phase: each phase adds its own rows, under its own banner, as part of its definition of
| done, and never edits another phase's.
|
| Row shape:
|   'route'         route name
|   'panel'         admin | collaborator | student | teacher | client | public
|   'kind'          index | show | form | board | calendar | wizard | print | public | export | dashboard | statement
|   'params'        fn (?object $fixture = null): array — the route parameters (and query) of one real
