|   'query_budget'  PRF-01's ceiling; the kind's default unless a 'budget_reason' says otherwise (Phase 3's
|                   rows were measured warm, as a Super Admin, on the seeded site: every one is within it)
|   'responsive'    in the responsive sweep
|   'a11y'          in the accessibility sweep
|   'idor'          ['owner' => the ownership column] or ['owner' => null] for a screen with no owner scope
|   'response'      html | json | csv | text | xml — what a GET answers (sweeps that parse HTML skip the rest)
|   'expect'        (optional) the status the sweep should expect on the standard fixture when it is not 200
|
*/

